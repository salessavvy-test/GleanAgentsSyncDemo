def add_numbers(a, b):
    """
    Add two numbers together.

    Args:
        a: First number
        b: Second number

    Returns:
        Sum of a and b
    """
    return a + b


if __name__ == "__main__":
    # Example usage
    num1 = 5
    num2 = 7
    result = add_numbers(num1, num2)
    print(f"{num1} + {num2} = {result}")
